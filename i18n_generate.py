#!/usr/bin/env python3
"""Generate the runtime i18n bundle from i18n-zh.py into site/assets/js/i18n-data.js.

The generated file is a single self-contained JS object. No network, no fetch,
no dependency — consistent with the site's zero-runtime-dependency promise.
"""
from pathlib import Path
import importlib.util
import json

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "site" / "assets" / "js" / "i18n-data.js"

spec = importlib.util.spec_from_file_location("i18n_zh", ROOT / "i18n-zh.py")
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)

payload = {"shared": mod.SHARED, "ui": mod.UI, "pages": mod.PAGES}
js = ("/* Generated by i18n_generate.py from i18n-zh.py. Do not edit by hand. */\n"
      "window.I18N_DATA = " + json.dumps(payload, ensure_ascii=False, indent=2) + ";\n")
OUT.write_text(js, encoding="utf-8")
print(f"generated {OUT.relative_to(ROOT)} ({OUT.stat().st_size:,} bytes)")
print(f"pages: {len(mod.PAGES)} | blocks: {sum(len(v) for v in mod.PAGES.values())} "
      f"| shared: {len(mod.SHARED)}")
